void cinema_unpack_packed4(const uint8_t *packed, uint8_t *out)
{
    uint16_t i;

    for (i = 0; i < CINEMA_V2_PACKED_BYTES; ++i) {
        uint16_t w = expand4[packed[i]];

        *out++ = (uint8_t)w;
        *out++ = (uint8_t)(w >> 8);
    }
}
