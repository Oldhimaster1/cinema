void cinema_draw_packed4_scaled2x(const uint8_t *packed,
                                   uint8_t *framebuffer,
                                   uint16_t framebuffer_stride,
                                   uint16_t y_offset)
{
    /* row0 is advanced by 2*stride per iteration (an add) instead of
     * recomputed via (y_offset + y*2)*stride (a 32-bit multiply) each
     * iteration -- ez80 has no native 32-bit multiply, so hoisting this
     * out of the 96-iteration loop removes 95 multiplies per frame. */
    uint8_t *row0 = framebuffer + (uint32_t)y_offset * framebuffer_stride;
    uint16_t y;

    for (y = 0; y < CINEMA_V2_HEIGHT; ++y) {
        uint8_t *row1 = row0 + framebuffer_stride;
        /* Two 16-bit stores through a walking destination pointer,
         * rather than four 8-bit stores: at 80 pairs x 96 rows that
         * halves the store count for the same output. Safe to write as
         * uint16_t because row0 (and therefore dst on every iteration,
         * which only ever advances by whole words) is always
         * even-aligned in practice: framebuffer_stride (GFX_LCD_WIDTH,
         * 320) and y_offset (V2_Y_OFFSET, 24) are both even, and every
         * real framebuffer this is called with (gfx_vbuffer, and the
         * fixed-size test buffers that stand in for it) starts at an
         * aligned address like any ordinary array. */
        uint16_t *dst = (uint16_t *)row0;
        uint16_t pair;

        for (pair = 0; pair < CINEMA_V2_WIDTH / 2; ++pair) {
            const uint16_t *w = expand4_words[*packed++];

            *dst++ = w[0];
            *dst++ = w[1];
        }
        /* row1 is always an exact duplicate of the row0 we just built
         * (2x vertical scaling): one contiguous block copy instead of
         * recomputing every pixel a second time. */
        memcpy(row1, row0, CINEMA_V2_DEST_WIDTH);

        row0 += (uint32_t)framebuffer_stride * 2;
    }
}
